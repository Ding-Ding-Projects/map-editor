// Writes one Markdown file per guide article under docs/features/<category>/, an index per category and
// a top index, all from site/content.mjs (the same source as the website and the in-app Guide).
// Run: node scripts/feature-docs.mjs   (add --check to fail when the files on disk are out of date)
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { features } from '../site/content.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const yue = JSON.parse(readFileSync(path.join(root, 'site/content.yue.json'), 'utf8'));
const SITE = 'https://ding-ding-projects.github.io/map-editor/';
const slugOf = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

/** Every generated file as [relative path, text]. */
const PLAIN_NAME = { 'cheap-jor-matrix': 'low-cost-check-matrix' };

/** The inventory's lines as entries: id, title, section heading, status, what is there, what is missing. */
export function inventoryEntries(text = readFileSync(path.join(root, 'docs/features/INVENTORY.md'), 'utf8')) {
  const out = []; let section = '';
  for (const line of text.split('\n')) {
    const h = /^## (.+)$/.exec(line); if (h) { section = h[1].trim(); continue; }
    const m = /^`([a-z0-9-]+)` \| APPLIES: [^|]* \| STATUS: ([A-Z-]+) \| EVIDENCE: (.*) \| MISSING: (.*)$/.exec(line);
    if (!m) continue;
    // A few catalogue ids are the maintainer's own shorthand; their pages get a plain name and title instead.
    const page = PLAIN_NAME[m[1]] ?? m[1];
    const title = page.split('-').map((w, i) => (i ? w : w[0].toUpperCase() + w.slice(1))).join(' ');
    out.push({ id: m[1], page, title, section, status: m[2], evidence: m[3].trim(), missing: m[4].trim() });
  }
  return out;
}

export function featureDocs() {
  const out = [];
  const groups = [...new Set(features.map((f) => f.group))];
  const where = (f) => `${slugOf(f.group)}/${f.slug}.md`;
  for (const f of features) {
    const y = yue[f.slug];
    const related = (f.related ?? []).map((s) => features.find((x) => x.slug === s)).filter(Boolean);
    out.push([where(f), [
      `# ${f.title}${y?.title && y.title !== f.title ? ` · ${y.title}` : ''}`, '',
      `> ${f.summary}`, ...(y?.summary ? ['>', `> ${y.summary}`] : []), '',
      `Category: [${f.group}](README.md) · [Read on the website, with pictures](${SITE}${f.slug}/)`, '',
      ...f.body.flatMap(([h, t, img], i) => [`## ${h}`, '', t, '', ...(y?.body?.[i]?.[1] ? [y.body[i][1], ''] : []),
        ...(img?.src ? [`![${img.alt ?? h}](../../screenshots/${img.src})`, ''] : [])]),
      ...(related.length ? ['## Related', '', ...related.map((r) => `- [${r.title}](../${where(r)})`), ''] : []),
      '<!-- Generated by scripts/feature-docs.mjs from site/content.mjs. Edit the source, then run the script. -->', '',
    ].join('\n')]);
  }
  for (const g of groups) {
    const list = features.filter((f) => f.group === g);
    out.push([`${slugOf(g)}/README.md`, [`# ${g}`, '', `[All categories](../README.md)`, '', ...list.map((f) => `- [${f.title}](${f.slug}.md): ${f.summary}`), '',
      '<!-- Generated by scripts/feature-docs.mjs from site/content.mjs. -->', ''].join('\n')]);
  }
  // One page per line of the inventory, so every feature has a page whether or not the guide has an article on it.
  const inv = inventoryEntries();
  const sections = [...new Set(inv.map((e) => e.section))];
  const STATUS_WORD = { BUILT: 'Built', PARTIAL: 'Partly built', UNBUILT: 'Not built', 'N-A': 'Does not apply' };
  for (const e of inv) {
    out.push([`catalogue/${e.page}.md`, [
      `# ${e.title}`, '', `Status: **${STATUS_WORD[e.status] ?? e.status}** · Section: ${e.section} · [All features](README.md)`, '',
      '## What is there', '', e.evidence || 'Nothing yet.', '',
      '## What is missing', '', e.missing && e.missing !== '-' ? e.missing : 'Nothing.', '',
      `<!-- Generated by scripts/feature-docs.mjs from docs/features/INVENTORY.md (entry ${e.id}). Edit that line, then run the script. -->`, '',
    ].join('\n')]);
  }
  out.push(['catalogue/README.md', ['# Every feature, one page each', '', 'Made from [INVENTORY.md](../INVENTORY.md), which is the record of what is built and what is not.', '',
    `Built ${inv.filter((e) => e.status === 'BUILT').length} · partly built ${inv.filter((e) => e.status === 'PARTIAL').length} · not built ${inv.filter((e) => e.status === 'UNBUILT').length} · does not apply ${inv.filter((e) => e.status === 'N-A').length}`, '',
    ...sections.flatMap((sec) => [`## ${sec}`, '', ...inv.filter((e) => e.section === sec).map((e) => `- [${e.title}](${e.page}.md): ${STATUS_WORD[e.status] ?? e.status}`), '']),
    '<!-- Generated by scripts/feature-docs.mjs from docs/features/INVENTORY.md. -->', ''].join('\n')]);
  out.push(['README.md', ['# Feature guide', '', 'One page per feature, grouped by category. The same text is on the [website](' + SITE + ') and inside the app under Guide.', '',
    ...groups.flatMap((g) => [`## [${g}](${slugOf(g)}/README.md)`, '', ...features.filter((f) => f.group === g).map((f) => `- [${f.title}](${slugOf(g)}/${f.slug}.md)`), '']),
    'See also [INVENTORY.md](INVENTORY.md) for what is built and what is not, and [one page for every feature](catalogue/README.md).', '', '<!-- Generated by scripts/feature-docs.mjs from site/content.mjs. -->', ''].join('\n')]);
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dir = path.join(root, 'docs/features'); let stale = 0;
  for (const [rel, text] of featureDocs()) {
    const file = path.join(dir, rel);
    if (process.argv.includes('--check')) { if (!existsSync(file) || readFileSync(file, 'utf8') !== text) { console.error(`out of date: docs/features/${rel}`); stale++; } }
    else { mkdirSync(path.dirname(file), { recursive: true }); writeFileSync(file, text); }
  }
  if (stale) process.exit(1);
  console.log(process.argv.includes('--check') ? 'feature docs are up to date' : 'feature docs written');
}
